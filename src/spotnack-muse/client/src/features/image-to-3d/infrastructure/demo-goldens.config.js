/*
Demo-goldens configuration for the image-to-3D demo mode (hackathon demo
at 10:00, not the shipped pipeline).

Everything is bundled in demo-goldens/<id>/ so the demo runs fully
offline with no HTTP dependency:
- input_rgba.png: pre-cut golden input, downscaled to 512 px (RGBA kept).
- mesh.display.glb: matching display mesh (~80k faces, decimated from the
  cloud-GPU original) so Explore and Stage render on the phone.
DEMO_INPUT_MODULES / DEMO_MESH_MODULES map each golden id to its bundled
module. Static require paths so Metro includes each file in the app bundle,
like the mock food models. The binaries are git-ignored (local-only demo
artifacts); .easignore re-includes them for the EAS cloud build.
*/

