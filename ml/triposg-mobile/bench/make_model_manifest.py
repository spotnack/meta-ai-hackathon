"""Build models_manifest.json for the on-device model directory.

Reads the 25 AI Hub unit locations from an AI Hub manifest
(head/blk00-blk20/tail/vae_post/vae_query device/model.onnx + model.bin),
plus logs/spike/dinov2_encoder.onnx and pretrained_weights/u2net/u2net.onnx,
streams SHA-256 over every file, and writes the manifest (version,
per-file path/bytes/sha256, total bytes).

The device layout mirrors the manifest paths (v1, 25 units):
  <model_dir>/<stem>/model.onnx + model.bin   (25 units)
  <model_dir>/dinov2_encoder.onnx
  <model_dir>/u2net.onnx
  <model_dir>/models_manifest.json            (this file)

Merged layout (--merged-dir, v2): dit_chain.onnx + <stem>/model.bin for
the 23 transformer stems (no per-unit model.onnx); VAE units keep
<stem>/model.onnx + model.bin.

--js-out also emits a GENERATED frozen-JS copy of the manifest for the
app (src/features/image-to-3d/infrastructure/triposg-models.manifest.js),
so the model-management adapter verifies/downloads exactly these files
without bundling the full JSON. ~6 KB for the 52 files.

Run from the repo root (you run this; one-time host job, ~7 GB hashed):
~/anaconda3/envs/triposg-spike/bin/python \\
  ml/triposg-mobile/bench/make_model_manifest.py [--version NAME] \\
  [--aihub-manifest PATH] [--out PATH] [--js-out PATH]

v2 (w8a16 transformer units, v2-w8a16-50step):
~/anaconda3/envs/triposg-spike/bin/python \\
  ml/triposg-mobile/bench/make_model_manifest.py \\
  --version v2-w8a16-50step \\
  --aihub-manifest ml/triposg-mobile/logs/spike/aihub_w8a16/manifest_w8a16.json \\
  --out ml/triposg-mobile/logs/spike/models_manifest_w8a16.json --js-out \\
  <bundled triposg-models.manifest.js path>

v2 merged (one FP32 session, v2-fp32-merged-50step; DIR is merge_chain.py
output with dit_chain.onnx + <stem>/model.bin):
~/anaconda3/envs/triposg-spike/bin/python \\
  ml/triposg-mobile/bench/make_model_manifest.py \\
  --version v2-fp32-merged-50step \\
  --merged-dir ml/triposg-mobile/logs/spike/merged/fp32 \\
  --out ml/triposg-mobile/logs/spike/models_manifest_merged.json
"""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path("ml/triposg-mobile")
AIHUB_MANIFEST = ROOT / "logs" / "spike" / "aihub" / "manifest_b1.json"
DINOV2 = ROOT / "logs" / "spike" / "dinov2_encoder.onnx"
U2NET = ROOT / "pretrained_weights" / "u2net" / "u2net.onnx"
OUT = ROOT / "logs" / "spike" / "models_manifest.json"

STEMS = (
    ["head"] + [f"blk{i:02d}" for i in range(21)] + ["tail", "vae_post", "vae_query"]
)
# Transformer stems covered by dit_chain.onnx in merged mode.
CHAIN_STEMS = ["head"] + [f"blk{i:02d}" for i in range(21)] + ["tail"]
VAE_STEMS = ("vae_post", "vae_query")
# The u2net ONNX shipped by rembg 2.0.86 (single known-good binary).
U2NET_SHA256 = "8d10d2f3bb75ae3b6d527c77944fc5e7dcd94b29809d47a739a7a728a912b491"


def sha_of(path: Path) -> str:
    """Stream SHA-256 over a file."""
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def collect_merged_pairs(merged: Path, vae: dict) -> list:
    """(source, rel) pairs for merged mode: chain + bins + VAE units."""
    pairs = [(merged / "dit_chain.onnx", "dit_chain.onnx")]
    pairs += [
        (merged / stem / "model.bin", f"{stem}/model.bin") for stem in CHAIN_STEMS
    ]
    for stem in VAE_STEMS:
        entry = vae[stem]
        pairs += [
            (Path(entry["compiled_onnx"]), f"{stem}/model.onnx"),
            (Path(entry["model_bin"]), f"{stem}/model.bin"),
        ]
    return pairs


def add_file(files: list, src: Path, rel: str) -> None:
    """Hash one source file and append its manifest entry."""
    assert src.exists(), src
    print(f"hash {rel} ({src.stat().st_size >> 20} MB)")
    files.append({"path": rel, "bytes": src.stat().st_size, "sha256": sha_of(src)})


def js_copy(manifest: dict) -> str:
    """Render the GENERATED frozen-JS manifest copy for the app."""
    lines = [
        "// GENERATED by ml/triposg-mobile/bench/make_model_manifest.py — do not edit.",
        "// Bundled copy of models_manifest.json: the exact file list the",
        "// model-management adapter downloads and verifies. Regenerate with",
        "// `make_model_manifest.py --js-out <this file>` when the weights change.",
        "export const TRIPOSG_MODELS_MANIFEST = Object.freeze({",
        f'  version: "{manifest["version"]}",',
        f'  totalBytes: {manifest["total_bytes"]},',
        "  files: Object.freeze([",
    ]
    for entry in manifest["files"]:
        lines.append(
            "    Object.freeze({ "
            f'path: "{entry["path"]}", '
            f'bytes: {entry["bytes"]}, '
            f'sha256: "{entry["sha256"]}" '
            "}),"
        )
    lines += ["  ]),", "});", ""]
    return "\n".join(lines)


def main() -> None:
    """Hash every model file and write the manifest."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--version", default="v1-fp32-50step")
    parser.add_argument(
        "--aihub-manifest",
        default=None,
        help="AI Hub manifest with the 23 transformer units "
        f"(default {AIHUB_MANIFEST})",
    )
    parser.add_argument(
        "--vae-manifest",
        default=None,
        help="AI Hub manifest with vae_post/vae_query "
        "(default: same as --aihub-manifest; the w8a16 "
        "manifest has transformer units only, so its VAE "
        "entries fall back to the fp32 manifest)",
    )
    parser.add_argument("--out", default=None, help=f"manifest output (default {OUT})")
    parser.add_argument(
        "--merged-dir",
        default=None,
        help="merge_chain.py output dir (dit_chain.onnx + <stem>/model.bin "
        "for the 23 transformer stems); replaces the per-unit model.onnx "
        "entries with the merged layout",
    )
    parser.add_argument("--js-out", default=None)
    args = parser.parse_args()

    aihub_path = Path(args.aihub_manifest) if args.aihub_manifest else AIHUB_MANIFEST
    vae_path = Path(args.vae_manifest) if args.vae_manifest else AIHUB_MANIFEST
    out_path = Path(args.out) if args.out else OUT
    aihub = json.loads(aihub_path.read_text())["units"]
    vae = json.loads(vae_path.read_text())["units"] if vae_path != aihub_path else aihub
    files = []
    if args.merged_dir:
        for src, rel in collect_merged_pairs(Path(args.merged_dir), vae):
            add_file(files, src, rel)
    else:
        for stem in STEMS:
            entry = vae[stem] if stem in VAE_STEMS else aihub[stem]
            for key, rel in (
                ("compiled_onnx", f"{stem}/model.onnx"),
                ("model_bin", f"{stem}/model.bin"),
            ):
                add_file(files, Path(entry[key]), rel)
    for src, rel in (
        (DINOV2, "dinov2_encoder.onnx"),
        (U2NET, "u2net.onnx"),
    ):
        add_file(files, src, rel)
    u2net = files[-1]
    assert (
        u2net["sha256"] == U2NET_SHA256
    ), f"u2net.onnx sha mismatch: {u2net['sha256']} (want the rembg binary)"
    manifest = {
        "version": args.version,
        "files": files,
        "total_bytes": sum(f["bytes"] for f in files),
    }
    out_path.write_text(json.dumps(manifest, indent=2) + "\n")
    print(
        f"wrote {out_path}: {len(files)} files, "
        f"{manifest['total_bytes'] >> 30} GiB total, "
        f"version {args.version}"
    )
    if args.js_out:
        js_path = Path(args.js_out)
        js_path.write_text(js_copy(manifest))
        print(f"wrote {js_path}: {js_path.stat().st_size} bytes")


if __name__ == "__main__":
    main()
